// Writes docs/coverage-class9-maths.md from the assembled course, the answer-key alignment and the 2027 syllabus.
//   node scripts/coverage-report.mjs [bundle.json]
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = "content/class9-maths";
const bundle = JSON.parse(readFileSync(process.argv[2] ?? `${ROOT}/bundle.json`, "utf8"));
const syllabus = JSON.parse(readFileSync(`${ROOT}/syllabus-2027.json`, "utf8"));
const audit = existsSync(`${ROOT}/work/audit.json`) ? JSON.parse(readFileSync(`${ROOT}/work/audit.json`, "utf8")) : [];
const read = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null);

const rows = [], misprints = [], corrected = [], unresolved = [];
for (const c of bundle.subject.chapters) {
  const n = c.number;
  const sols = c.modules.flatMap((m) => m.solutions);
  const ex = sols.filter((s) => s.kind === "EXERCISE");
  const align = read(`${ROOT}/units/u-${n}-align.json`);
  // Logic gives the same exercise to several sub-lessons; count each question once.
  const items = align ? [...new Map(align.items.map((i) => [i.source, i])).values()] : [];
  const count = (st) => items.filter((i) => i.status === st || (st === "corrected" && i.status.startsWith("corrected"))).length;
  const withKey = items.filter((i) => i.bookAnswer).length;
  rows.push(`| ${n} ${c.title} | ${c.modules.length} | ${sols.filter((s) => s.kind === "EXAMPLE").length} | ${ex.length} | ${ex.filter((s) => s.checked).length} | ${withKey} | ${count("matches key")} | ${count("key misprint")} | ${count("corrected")} | ${count("unresolved")} | ${syllabus.excludedUnits.includes(n) ? "not examined" : ex.filter((s) => s.inExam !== false).length} | ${c.kit ? `${c.kit.definitions.length} / ${c.kit.formulas.length} / ${c.kit.important.length}` : "—"} |`);
  for (const i of items) {
    if (i.status === "key misprint") misprints.push(`- Unit ${n}, ${i.source}: the key prints "${i.bookAnswer}". ${i.examiner ?? ""}`.trim());
    if (i.status.startsWith("corrected")) corrected.push(`- Unit ${n}, ${i.source}: now "${i.replace?.answer ?? ""}"${i.replace?.question ? ` (question re-read from the page: "${i.replace.question}")` : ""}. ${i.examiner ?? ""}`.trim());
    if (i.status === "unresolved") unresolved.push(`- Unit ${n}, ${i.source}${i.bookAnswer ? `: book answer "${i.bookAnswer}"` : ""}. ${i.examiner ?? ""}`.trim());
  }
}

const boards = bundle.blueprints.filter((b) => b.id.startsWith("board-"));
const unitTests = bundle.blueprints.filter((b) => b.chapterId);
const auditLines = audit.filter((a) => a.examplesMissing?.length || a.gaps?.length || a.missing?.length)
  .map((a) => `- Unit ${a.unit}: ${[a.examplesMissing?.length ? `examples missing ${a.examplesMissing.join(", ")}` : "", a.gaps?.length ? `numbering gaps ${a.gaps.join(", ")}` : "", a.missing?.length ? `printed but not solved ${a.missing.join(", ")}` : ""].filter(Boolean).join("; ")}`);

const doc = `# Class 9 Mathematics: coverage report

Built from the Punjab textbook (Mathematics 9, National Curriculum 2023, English medium). This file is generated by \`scripts/coverage-report.mjs\` from the course bundle; do not edit by hand.

## What is covered

| Unit | Lessons | Worked examples | Exercise questions | With checked solutions | With a printed key answer | Match the key | Key misprints (explained) | Corrected | Book answer only | In the 2027 exam | Exam kit (definitions / formulas / important) |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

**Completeness audit.** Every exercise question number and part runs without gaps, every worked example runs 1…N, and every question printed in the book has a solution. Any exception is listed here:
${auditLines.length ? auditLines.join("\n") : "- None."}

## How every answer was aligned with the textbook's key

1. **The key, read twice.** The answer pages at the back of the book were read twice at high resolution: once as whole pages, once as top and bottom halves.
2. **An independent teacher's solutions** for the same book were read page by page. They are used only to check answers. They are never shown to students and never named.
3. **Every question compared.** Our checked final answer was compared with the key and with the independent answer, allowing for equivalent forms and log-table rounding.
4. **Disagreements went to an examiner pass** with high reasoning effort. Where the key and the independent solution agreed against us, the examiner was given the printed textbook page so it could read the question itself, which catches misread questions.
5. **Outcome:**
   - If our answer was wrong, the question was solved again towards the right answer and re-checked.
   - If the key itself is wrong, students see the right working and a note: "Your textbook's answer key shows …".
   - Anything still unclear shows the book's answer only.

Every solution shows a **Book answer** line wherever the key prints one.

## Key misprints (the right working is shown, with a note)

${misprints.length ? misprints.join("\n") : "- None."}

## Corrected to match the right answer

${corrected.length ? corrected.join("\n") : "- None."}

## Book answer only (no checked working yet)

${unresolved.length ? unresolved.join("\n") : "- None."}

## Annual Exam 2027

**Source.** The smart / reduced syllabus and paper instructions published by the Punjab Education, Curriculum, Training & Assessment Authority.

**Paper.**
- 75 marks in 2 hours 30 minutes.
- 15 MCQs (20 minutes).
- Q2–Q4: three groups of 9 short questions, attempt 6 of each (2 marks each).
- Part II: attempt 2 of Q5–Q7 (8 marks each, as two 4-mark parts).
- Part III: attempt 1 of Q8–Q9.
- Unit 8 (Logic) is not examined.

**What the app does with it.**
- Content the syllabus leaves out stays in the app, labelled "Not in this year's exam · practice".
- The study plan skips it.
- Unit tests and board papers never use it.

**Papers.**
- **Board papers:** ${boards.length} (${boards.map((b) => b.title).join("; ")}). Each follows the per-unit layout exactly.
- **Unit tests:** ${unitTests.length}.

## Excluded by the 2027 smart syllabus

${Object.entries(syllabus.excluded).map(([u, list]) => `- Unit ${u}: ${list.join(", ").replace("*", "whole unit")}`).join("\n")}
`;
writeFileSync("docs/coverage-class9-maths.md", doc);
console.log(`docs/coverage-class9-maths.md: ${misprints.length} misprints, ${corrected.length} corrected, ${unresolved.length} book-answer-only`);
